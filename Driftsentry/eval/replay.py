"""Replay recorded genuine traffic inside an episode.

Two questions need real user traffic inside the episode, not just probes.

RQ2 asks whether active probing beats passive monitoring. Passive monitoring
watches real calls, so with no real calls it has nothing to watch and would
score zero by construction - which would look like a finding and be an
artefact of the experiment.

RQ3's recall half asks what an L6 attacker costs. L6 stays benign for
anything it recognises as a probe. In a probe-only episode it therefore never
fires at all, every episode classifies as ``never_triggered``, and recall is
undefined exactly where the question is. The attacker has to be given
something it believes is a genuine user.

Where the traffic comes from
    The calls recorded during the T5 collection, grouped by the session that
    produced them. Replaying a whole session rather than a shuffled bag of
    calls matters: the session feature family reads calls_before and
    distinct_tools_before, and a session of the wrong shape would look
    unlike anything a model actually produced.

    Values are replayed verbatim, which is safe here because every one was
    generated by a model against the adversarial server's synthetic records.
    Nothing in the corpus came from a person.

What is NOT replayed
    The model. Re-running Ollama inside every episode would make an already
    long experiment far longer, and the model's choices are not what is under
    test - the traffic they produced is. The replay sends the same calls the
    model made, through the same proxy, with the same client identity.
"""
from __future__ import annotations

import json
import random
import sys
from collections import defaultdict
from pathlib import Path
from typing import Any

#: Where the collection put its labelled rows.
DEFAULT_CORPUS = Path(__file__).resolve().parent.parent / "eval_results" / "rq3" / "dataset.jsonl"

GENUINE = 0


def load_sessions(corpus: str | Path | None = None) -> list[list[dict[str, Any]]]:
    """Genuine sessions from the collection, each a list of calls in order.

    A session is one process instance: the calls one model made while
    answering one task.
    """
    path = Path(corpus) if corpus else DEFAULT_CORPUS
    if not path.is_file():
        return []

    by_session: dict[Any, list[dict[str, Any]]] = defaultdict(list)
    for line in path.read_text(encoding="utf-8").splitlines():
        if not line.strip():
            continue
        row = json.loads(line)
        if row.get("label") != GENUINE:
            continue
        tool, args = row.get("tool"), row.get("args")
        if not tool or not isinstance(args, dict):
            continue
        by_session[row.get("group")].append(
            {"tool": tool, "args": args, "t": row.get("t", 0.0)})

    sessions = []
    for calls in by_session.values():
        calls.sort(key=lambda c: c["t"])
        sessions.append([{"tool": c["tool"], "args": c["args"]} for c in calls])
    # Deterministic order, so an episode seed selects the same sessions.
    sessions.sort(key=lambda s: (len(s), json.dumps(s, sort_keys=True)))
    return sessions


def choose_sessions(
    sessions: list[list[dict[str, Any]]],
    n: int,
    *,
    seed: int,
    avoid_tools: set[str] | None = None,
) -> list[list[dict[str, Any]]]:
    """Pick ``n`` sessions reproducibly.

    ``avoid_tools`` supports the T11 case: an attack aimed at a tool the agent
    never calls, where the point is that probing sees it and passive
    monitoring cannot.
    """
    pool = sessions
    if avoid_tools:
        pool = [s for s in sessions if not any(c["tool"] in avoid_tools for c in s)]
    if not pool:
        return []
    rng = random.Random(seed)
    return [pool[rng.randrange(len(pool))] for _ in range(n)]


async def replay_session(
    calls: list[dict[str, Any]],
    launch: dict[str, Any],
    *,
    client_info: dict[str, str],
    timeout: float = 60.0,
) -> list[dict[str, Any]]:
    """Send one recorded session through the proxy, as the agent would have.

    Returns one record per call. A failed call is recorded rather than raised:
    the traffic still reached the server, which is what the attacker saw and
    what passive monitoring observed.
    """
    import time

    from mcp import ClientSession, types
    from mcp.client.stdio import StdioServerParameters, stdio_client

    out: list[dict[str, Any]] = []
    params = StdioServerParameters(
        command=launch["command"], args=launch["args"],
        cwd=launch.get("cwd"), env=launch.get("env"))

    async with stdio_client(params, errlog=None) as (read, write):
        async with ClientSession(read, write, client_info=types.Implementation(
                name=client_info["name"], version=client_info["version"])) as session:
            await session.initialize()
            for call in calls:
                started = time.perf_counter()
                try:
                    result = await session.call_tool(call["tool"], call["args"])
                    text = "\n".join(
                        getattr(b, "text", "") or ""
                        for b in (getattr(result, "content", None) or []))
                    failed = bool(getattr(result, "isError", False))
                except Exception as exc:
                    text, failed = f"error: {exc}", True
                out.append({
                    "tool": call["tool"],
                    "args": call["args"],
                    "text": text,
                    "failed": failed,
                    "latency_s": time.perf_counter() - started,
                })
    return out


def passive_findings(ds_home: str | Path, server_id: str) -> dict[str, Any]:
    """What passive monitoring saw, read from the proxy's sidecar.

    The sidecar rather than the shutdown record: a client disconnect
    terminates the proxy process, so the end-of-session record frequently
    never gets written. T1 has the measurement.
    """
    path = Path(ds_home) / "logs" / f"{server_id}.passive.json"
    if not path.is_file():
        return {"summary": {}, "findings": [], "available": False}
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except Exception:
        return {"summary": {}, "findings": [], "available": False}
    return {"summary": data.get("summary", {}),
            "findings": data.get("findings", []),
            "available": True}
